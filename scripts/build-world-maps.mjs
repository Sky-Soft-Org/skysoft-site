// Builds the two maps of the clients section from Natural Earth (public domain), via world-atlas:
//   src/data/worldDots.js    the dotted world map (ClientsDotted.jsx), from the 1:110m shapes
//   src/data/worldShapes.js  the simple map (ClientsSimple.jsx): land and the Middle East client
//                            countries as solid shapes, from the 1:50m shapes, Brazil to the Gulf
// Both use the Equal Earth projection centred on Greenwich.
//
// Rebuild after changing a grid, the frame or the countries:
//   npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3
//   node scripts/build-world-maps.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains, geoEqualEarthRaw, geoPath, geoProjection } from 'd3-geo';

const require = createRequire(import.meta.url);
const rad = Math.PI / 180;
const project = geoEqualEarthRaw;
const round = (n, d) => Number(n.toFixed(d));
const write = (file, text) => fs.writeFileSync(new URL(`../src/data/${file}`, import.meta.url), text);

// ---------- Dotted world map ----------
// Dots on a hex grid, kept where their centre falls on land; Egypt and Saudi Arabia apart
{
  const topo = require('world-atlas/countries-110m.json');
  const COLS = 200; // dots across the full width of the map
  const NORTH = 84; // the tip of Greenland
  const SOUTH = -57; // just below Cape Horn, so no Antarctica
  const MAIN = ['818', '682']; // Egypt, Saudi Arabia (ISO 3166 numeric codes): most clients are here
  const WIDTH = 1000; // viewBox width

  const xMax = project(Math.PI, 0)[0];
  const yTop = project(0, NORTH * rad)[1];
  const yBottom = project(0, SOUTH * rad)[1];
  const k = WIDTH / (2 * xMax);
  const height = (yTop - yBottom) * k;
  const step = WIDTH / COLS;
  const rowStep = (step * Math.sqrt(3)) / 2;
  const rows = Math.floor(height / rowStep);

  const land = feature(topo, topo.objects.land);
  const main = feature(topo, topo.objects.countries).features.filter((f) => MAIN.includes(f.id));
  const landBits = new Uint8Array(Math.ceil((rows * COLS) / 8));
  const mainBits = new Uint8Array(landBits.length);
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < COLS; c++) {
      const x = (c + 0.5 + (r % 2) * 0.5) * step; // odd rows shift half a step
      const y = (r + 0.5) * rowStep;
      const [lambda, phi] = project.invert(x / k - xMax, yTop - y / k);
      if (Math.abs(lambda) > Math.PI) continue; // outside the map's outline
      const point = [lambda / rad, phi / rad];
      if (!geoContains(land, point)) continue;
      const i = r * COLS + c;
      const bits = main.some((f) => geoContains(f, point)) ? mainBits : landBits;
      bits[i >> 3] |= 128 >> (i & 7);
    }
  }

  const b64 = (bits) => Buffer.from(bits).toString('base64');
  write('worldDots.js', `// Generated by scripts/build-world-maps.mjs from Natural Earth 1:110m (public domain). Do not edit by hand.
// Land dots for the dotted map: one bit per spot on a hex grid, row by row, in base64.
// \`main\` holds the dots inside Egypt and Saudi Arabia, \`land\` all the others.
// k, xMax and yTop turn Equal Earth coordinates into viewBox units (see ClientsDotted.jsx).
export const WORLD = {
  width: ${WIDTH},
  height: ${round(height, 2)},
  cols: ${COLS},
  rows: ${rows},
  step: ${round(step, 4)},
  rowStep: ${round(rowStep, 4)},
  k: ${round(k, 4)},
  xMax: ${round(xMax, 6)},
  yTop: ${round(yTop, 6)},
  land: '${b64(landBits)}',
  main: '${b64(mainBits)}',
};
`);
  console.log('worldDots.js', { rows, cols: COLS });
}

// ---------- Simple map ----------
// Land as one shape with no borders drawn, and the Middle East client countries over it
{
  const topo = require('world-atlas/countries-50m.json');
  const FRAME = { west: -76, east: 64, north: 44, south: -36 }; // Brazil to the Gulf
  const COUNTRIES = { eg: '818', sa: '682', jo: '400', ae: '784' };
  const WIDTH = 1000; // viewBox width
  const TOLERANCE = 0.35; // how far (viewBox units) a simplified coastline may stray
  const SPECK = 1.2; // islands smaller than this (square viewBox units) are left out

  const xMin = project(FRAME.west * rad, 0)[0];
  const xMax = project(FRAME.east * rad, 0)[0];
  const yMax = project(0, FRAME.north * rad)[1];
  const yMin = project(0, FRAME.south * rad)[1];
  const k = WIDTH / (xMax - xMin);
  const height = (yMax - yMin) * k;
  const projection = geoProjection(project)
    .scale(k)
    .translate([-xMin * k, yMax * k])
    .clipExtent([[0, 0], [WIDTH, height]]);

  // Douglas–Peucker: drops points that sit within `tol` of the line through their neighbours
  const simplify = (pts, tol) => {
    if (pts.length < 4) return pts;
    const keep = new Uint8Array(pts.length);
    keep[0] = 1;
    keep[pts.length - 1] = 1;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
      const [a, b] = stack.pop();
      const [ax, ay] = pts[a];
      const [bx, by] = pts[b];
      const len = Math.hypot(bx - ax, by - ay);
      let far = 0;
      let at = -1;
      for (let i = a + 1; i < b; i++) {
        const [px, py] = pts[i];
        const d = len < 1e-9 ? Math.hypot(px - ax, py - ay) : Math.abs((by - ay) * px - (bx - ax) * py + bx * ay - by * ax) / len;
        if (d > far) {
          far = d;
          at = i;
        }
      }
      if (far > tol && at > 0) {
        keep[at] = 1;
        stack.push([a, at], [at, b]);
      }
    }
    return pts.filter((_, i) => keep[i]);
  };
  const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => {
    const [nx, ny] = pts[(i + 1) % pts.length];
    return s + x * ny - nx * y;
  }, 0)) / 2;

  // Projects, clips to the frame and simplifies a shape; returns compact SVG path data
  const toPath = (geo) => {
    const rings = [];
    let ring = null;
    geoPath(projection, {
      moveTo(x, y) { ring = [[x, y]]; rings.push(ring); },
      lineTo(x, y) { ring.push([x, y]); },
      closePath() {},
      arc() {},
    })(geo);
    let d = '';
    let points = 0;
    for (const raw of rings) {
      const pts = simplify(raw, TOLERANCE);
      if (pts.length < 3 || area(pts) < SPECK) continue;
      let [px, py] = pts[0].map((v) => Math.round(v * 10));
      d += `M${px / 10} ${py / 10}`;
      let step = '';
      for (const [x, y] of pts.slice(1)) {
        const nx = Math.round(x * 10);
        const ny = Math.round(y * 10);
        if (nx === px && ny === py) continue;
        step += ` ${(nx - px) / 10} ${(ny - py) / 10}`;
        px = nx;
        py = ny;
        points += 1;
      }
      d += `l${step.trim()}z`;
    }
    return { d: d.replace(/ -/g, '-'), points };
  };

  const countries = feature(topo, topo.objects.countries).features;
  const shapes = { land: toPath(feature(topo, topo.objects.land)) };
  for (const [key, id] of Object.entries(COUNTRIES)) {
    shapes[key] = toPath(countries.find((f) => f.id === id));
  }

  write('worldShapes.js', `// Generated by scripts/build-world-maps.mjs from Natural Earth 1:50m (public domain). Do not edit by hand.
// The simple map: land from Brazil to the Gulf as one shape with no borders drawn, and the
// Middle East client countries (Egypt, Saudi Arabia, Jordan, UAE) as their own shapes over it.
// k, xMin and yMax turn Equal Earth coordinates into viewBox units (see ClientsSimple.jsx).
export const SHAPES = {
  width: ${WIDTH},
  height: ${round(height, 2)},
  k: ${round(k, 4)},
  xMin: ${round(xMin, 6)},
  yMax: ${round(yMax, 6)},
${Object.entries(shapes).map(([key, s]) => `  ${key}: '${s.d}',`).join('\n')}
};
`);
  console.log('worldShapes.js', Object.fromEntries(Object.entries(shapes).map(([key, s]) => [key, `${s.points} points, ${s.d.length} chars`])));
}
